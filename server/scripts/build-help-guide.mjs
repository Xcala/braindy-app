// Builds server/src/help/guideData.ts from the tutorial catalog (video/tutoriales/catalogo.mjs), so the help assistant
// knows exactly what the tutorial videos teach. Run it again after the catalog changes:
//   node server/scripts/build-help-guide.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { SECCIONES, NOVEDADES } = await import(pathToFileURL(join(here, '../../video/tutoriales/catalogo.mjs')).href);

const block = (v, lang) => {
  const where = v.paths.length ? ` · ${lang === 'es' ? 'páginas' : 'pages'}: ${v.paths.join(', ')}` : '';
  const menu = lang === 'es' ? v.nav : v.navEn;
  return [
    `## ${v.titulo[lang]} · ${lang === 'es' ? 'menú' : 'menu'}: ${menu}${where} · video: /learn/tut-${v.id}`,
    v.resumen[lang],
    ...v.escenas.map((e) => `- ${e[lang]}${e.ui ? ` (${lang === 'es' ? 'en pantalla' : 'on screen'}: «${e.ui}»)` : ''}`),
  ].join('\n');
};

const all = [...SECCIONES, ...NOVEDADES];
const out = `// Generated by server/scripts/build-help-guide.mjs from video/tutoriales/catalogo.mjs. Do not edit by hand.
export const GUIDE_SECTIONS: Record<'es' | 'en', string[]> = ${JSON.stringify({ es: all.map((v) => block(v, 'es')), en: all.map((v) => block(v, 'en')) }, null, 1)};
`;
writeFileSync(join(here, '../src/help/guideData.ts'), out);
console.log(`help guide: ${all.length} sections`);
